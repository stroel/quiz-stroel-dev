/**
 * Every flag the quiz knows. `code` is the file name in flag-icons
 * (`flags/4x3/<code>.svg`), which is the lower-case ISO 3166-1 code for
 * countries and territories.
 *
 * Names are written out instead of taken from `Intl.DisplayNames('nl')`: ICU
 * returns forms like "Myanmar (Birma)" or "Hongkong SAR van China" that nobody
 * types, and its output differs between engines. Aliases are the other names
 * people actually use; the matcher accepts any of them.
 */

export type Region =
  'europa' | 'azie' | 'afrika' | 'noord-amerika' | 'midden-amerika' | 'zuid-amerika' | 'oceanie';

/** `land` is the base set: the 193 UN members plus Vatican City and Palestine. */
export type FlagKind = 'land' | 'betwist' | 'gebied' | 'organisatie';

export interface FlagEntry {
  code: string;
  name: string;
  kind: FlagKind;
  /** Transcontinental countries carry two regions. Organisations carry none. */
  regions: Region[];
  aliases?: string[];
  microstate?: boolean;
}

