/**
 * Famous quotes for the "who said it?" quiz. Every quote is checked against
 * Wikiquote, Wikipedia or a news source for its wording, who said it and the
 * year; quotes that are commonly misattributed are left out rather than
 * credited to someone nobody knows. See docs/citaten.md.
 *
 * Ids are stable: they key the history.
 */

/** The series on the setup screen. */
export type QuoteGroup = 'wereld' | 'belgie-nederland' | 'film-tv';

export const QUOTE_GROUPS: QuoteGroup[] = ['wereld', 'belgie-nederland', 'film-tv'];

/** What the answer is: the person who said it, or the film or series it is from. */
export type QuoteKind = 'persoon' | 'film' | 'serie';

export type QuoteLanguage = 'nl' | 'en' | 'fr' | 'de' | 'la' | 'es' | 'it';

export interface Quote {
  id: string;
  /** As it was said, in the original language. */
  text: string;
  lang: QuoteLanguage;
  /** Dutch translation, for anything not in Dutch or English. */
  translation?: string;
  /** The answer: a person's name as it is usually written, or a film or series title. */
  by: string;
  /** Other accepted answers: the surname alone, other spellings, the character's name. */
  also?: string[];
  kind: QuoteKind;
  group: QuoteGroup;
  /** Negative before Christ; absent for a saying with no known first use (Cruijff). */
  year?: number;
  /** A few Dutch words on when or where, shown once answered. */
  context: string;
}

/** Who said it, with the names that also count, so a person with five quotes is written once. */
interface Source {
  by: string;
  also?: string[];
  kind: QuoteKind;
}

const person = (by: string, ...also: string[]): Source => ({
  by,
  kind: 'persoon',
  ...(also.length > 0 && { also }),
});
const film = (by: string, ...also: string[]): Source => ({
  by,
  kind: 'film',
  ...(also.length > 0 && { also }),
});
const series = (by: string, ...also: string[]): Source => ({
  by,
  kind: 'serie',
  ...(also.length > 0 && { also }),
});

/** One quote; the source spreads in who said it. English unless `lang` says otherwise. */
function quote({ lang = 'en', ...rest }: Omit<Quote, 'lang'> & { lang?: QuoteLanguage }): Quote {
  return { ...rest, lang };
}

