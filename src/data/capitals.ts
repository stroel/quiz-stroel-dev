/**
 * The capital of every country and territory in FLAGS (organisations have
 * none), in the same order. `code` links an entry to its flag and its Dutch
 * country name.
 *
 * `name` follows the Taalunie list of capitals where it has a Dutch form
 * (Brussel, Peking, Kopenhagen). Aliases are the local and English spellings
 * people actually type; the matcher already forgives typos, accents, hyphens
 * and sound-alike spellings, so those are not listed.
 *
 * `alsoAccepted` holds a second capital that counts as correct too: a seat of
 * government next to the constitutional capital, or the city a contested
 * capital is commonly confused with. Its entries are plain names; an English
 * spelling that differs (Cape Town) is listed there as well.
 */

export interface CapitalEntry {
  /** Flag code from FLAGS. */
  code: string;
  /** Capital as a Dutch speaker writes it, with the Dutch exonym where one is common. */
  name: string;
  /** Other spellings of the same city: local or English forms people actually type. */
  aliases?: string[];
  /** Other official or commonly accepted capitals, also accepted as correct. */
  alsoAccepted?: string[];
  /** The capital equals or contains the country name, so asking for it gives itself away. */
  trivial?: true;
  /** One short Dutch note shown after answering, only where the answer surprises or is contested. */
  note?: string;
}

